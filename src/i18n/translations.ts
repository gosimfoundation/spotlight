type TranslationKey = keyof (typeof translations)["en"];

export function getTranslations(locale: Locale) {
  const t = translations[locale] || translations[defaultLocale];
  return (key: TranslationKey, params?: Record<string, string | number>): string => {
    let value = t[key] || translations[defaultLocale][key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        value = value.replace(`{${k}}`, String(v)) as typeof value;
      });
    }
    return value;
  };
}

export function getLocaleFromUrl(url: URL): Locale {
  const [, segment] = url.pathname.split("/");
  if (segment === "fr" || segment === "zh") return segment;
  return "en";
}

export function getLocalizedPath(path: string, locale: Locale): string {
  const cleanPath = path.replace(/^\/(fr|zh)/, "") || "/";
  if (locale === "fr" && cleanPath.startsWith("/shenzhen2026/apply")) return `/en${cleanPath}`;
  if (locale === "fr" && cleanPath.startsWith("/shenzhen2026")) return cleanPath;
  if (locale === "en") return cleanPath;
  return `/${locale}${cleanPath}`;
}
